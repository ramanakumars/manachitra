export type ColormapName = keyof typeof COLORMAP_STOPS;

export const COLORMAPS = Object.keys(COLORMAP_STOPS) as ColormapName[];

/** Number of entries in a palette texture (one per 8-bit display level). */
export const PALETTE_SIZE = 256;

/**
 * Expand a colormap's stops to PALETTE_SIZE colours ([r, g, b, 1]) by linear
 * interpolation, for use with the `palette` style operator.
 * @param name Colormap name; throws if unknown.
 */
export function palette(name: string): Rgba[] {
    const stops = (COLORMAP_STOPS as Record<string, Rgb[] | undefined>)[name];
    if (!stops) {
        throw new Error(
            `Unknown colormap "${name}". Known: ${COLORMAPS.join(", ")}`,
        );
    }
    const last = stops.length - 1;
    return Array.from({ length: PALETTE_SIZE }, (_, i): Rgba => {
        const x = (i / (PALETTE_SIZE - 1)) * last;
        const k = Math.min(Math.floor(x), last - 1);
        const f = x - k;
        const [lo, hi] = [stops[k], stops[k + 1]];
        const c = (j: number) => Math.round(lo[j] + (hi[j] - lo[j]) * f);
        return [c(0), c(1), c(2), 1];
    });
}
